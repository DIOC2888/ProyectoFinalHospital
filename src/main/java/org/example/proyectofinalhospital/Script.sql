CREATE DATABASE hospitalbd;

CREATE SCHEMA administracion;

CREATE SCHEMA catalogos;

CREATE SCHEMA seguridad;


--1. especialidad
CREATE TABLE catalogos.especialidad (
    id_especialidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);


--2. pacientes
CREATE TABLE administracion.paciente (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    documento VARCHAR(30) NOT NULL UNIQUE,
    fecha_nacimiento DATE NOT NULL,
    telefono VARCHAR(20),
    correo VARCHAR(100),
    direccion VARCHAR(255),
    contacto_emergencia VARCHAR(100),
    telefono_emergencia VARCHAR(20),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

--3 medicos
CREATE TABLE administracion.medico (
    id_medico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    codigo_medico VARCHAR(30) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    correo VARCHAR(100),
    id_especialidad INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_medico_especialidad
    FOREIGN KEY (id_especialidad)
    REFERENCES catalogos.especialidad(id_especialidad)
);

--4. citas
CREATE TABLE administracion.cita (
     id_cita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     id_paciente INTEGER NOT NULL,
     id_medico INTEGER NOT NULL,
     fecha_hora TIMESTAMP NOT NULL,
     motivo VARCHAR(255),
     estado VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADA',
     observaciones VARCHAR(255),
     fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

     CONSTRAINT fk_cita_paciente
         FOREIGN KEY (id_paciente)
             REFERENCES administracion.paciente(id_paciente),

     CONSTRAINT fk_cita_medico
         FOREIGN KEY (id_medico)
             REFERENCES administracion.medico(id_medico),

     CONSTRAINT chk_estado_cita
         CHECK (estado IN (
                           'PROGRAMADA',
                           'CONFIRMADA',
                           'COMPLETADA',
                           'CANCELADA',
                           'NO_ASISTIO'
             )),

     CONSTRAINT chk_horario_cita
         CHECK (
             EXTRACT(MINUTE FROM fecha_hora) IN (0, 30)
                 AND EXTRACT(SECOND FROM fecha_hora) = 0
             )
);

--5.
CREATE TABLE seguridad.usuario (
   id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   username VARCHAR(50) NOT NULL UNIQUE,
   password_hash VARCHAR(255) NOT NULL,
   rol VARCHAR(20) NOT NULL,
   activo BOOLEAN NOT NULL DEFAULT TRUE,
   fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

   CONSTRAINT chk_rol_usuario
       CHECK (rol IN (
                      'ADMINISTRADOR',
                      'RECEPCIONISTA'
           ))
);


